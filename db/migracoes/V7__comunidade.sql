-- =============================================================================
--  V7: comunidade e engajamento, como no protótipo de alta fidelidade.
--
--  - favoritos: pontos que o visitante marca com a estrela, no card;
--  - problemas: "reportar problema" no card do ponto (RF10 da Especificação);
--  - avisos: avisos oficiais da administração, no topo do feed;
--  - publicações, curtidas, comentários e denúncias: o feed "No parque hoje";
--  - seguidores: os "amigos" do perfil e do ranking;
--  - tb_usuario.perfil_publico: quem não quer aparecer no ranking nem ter o perfil
--    visto por outras pessoas desliga em Ajustes.
-- =============================================================================

ALTER TABLE tb_usuario ADD COLUMN perfil_publico BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE tb_favorito (
    id_usuario BIGINT       NOT NULL,
    id_poi     BIGINT       NOT NULL,
    momento    TIMESTAMP(6) NOT NULL,

    CONSTRAINT pk_favorito PRIMARY KEY (id_usuario, id_poi),
    CONSTRAINT fk_favorito_usuario FOREIGN KEY (id_usuario) REFERENCES tb_usuario (id),
    CONSTRAINT fk_favorito_poi FOREIGN KEY (id_poi) REFERENCES tb_ponto_interesse (id)
);

CREATE TABLE tb_problema (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    id_usuario  BIGINT       NOT NULL,
    id_poi      BIGINT       NOT NULL,
    tipo        VARCHAR(30)  NOT NULL,
    descricao   VARCHAR(600),
    situacao    VARCHAR(20)  NOT NULL,
    momento     TIMESTAMP(6) NOT NULL,
    resolvido   TIMESTAMP(6),

    CONSTRAINT pk_problema PRIMARY KEY (id),
    CONSTRAINT fk_problema_usuario FOREIGN KEY (id_usuario) REFERENCES tb_usuario (id),
    CONSTRAINT fk_problema_poi FOREIGN KEY (id_poi) REFERENCES tb_ponto_interesse (id),
    CONSTRAINT ck_problema_tipo CHECK (tipo IN ('LIMPEZA', 'QUEBRADO', 'FECHADO', 'SEGURANCA', 'ACESSIBILIDADE', 'INFORMACAO', 'OUTRO')),
    CONSTRAINT ck_problema_situacao CHECK (situacao IN ('ABERTO', 'RESOLVIDO', 'DESCARTADO'))
);

CREATE INDEX ix_problema_situacao ON tb_problema (situacao, momento DESC);

CREATE TABLE tb_aviso (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    titulo     VARCHAR(120) NOT NULL,
    texto      VARCHAR(600) NOT NULL,
    id_poi     BIGINT,
    inicio     TIMESTAMP(6) NOT NULL,
    fim        TIMESTAMP(6),
    id_autor   BIGINT       NOT NULL,

    CONSTRAINT pk_aviso PRIMARY KEY (id),
    CONSTRAINT fk_aviso_poi FOREIGN KEY (id_poi) REFERENCES tb_ponto_interesse (id),
    CONSTRAINT fk_aviso_autor FOREIGN KEY (id_autor) REFERENCES tb_usuario (id)
);

CREATE TABLE tb_publicacao (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    id_usuario  BIGINT       NOT NULL,
    texto       VARCHAR(500) NOT NULL,
    id_poi      BIGINT,
    momento     TIMESTAMP(6) NOT NULL,
    -- Ocultada por denúncias ou pela administração: some do feed, mas fica no banco
    oculta      BOOLEAN      NOT NULL DEFAULT FALSE,

    CONSTRAINT pk_publicacao PRIMARY KEY (id),
    CONSTRAINT fk_publicacao_usuario FOREIGN KEY (id_usuario) REFERENCES tb_usuario (id),
    CONSTRAINT fk_publicacao_poi FOREIGN KEY (id_poi) REFERENCES tb_ponto_interesse (id)
);

CREATE INDEX ix_publicacao_momento ON tb_publicacao (momento DESC);

CREATE TABLE tb_curtida (
    id_publicacao BIGINT NOT NULL,
    id_usuario    BIGINT NOT NULL,

    CONSTRAINT pk_curtida PRIMARY KEY (id_publicacao, id_usuario),
    CONSTRAINT fk_curtida_publicacao FOREIGN KEY (id_publicacao) REFERENCES tb_publicacao (id),
    CONSTRAINT fk_curtida_usuario FOREIGN KEY (id_usuario) REFERENCES tb_usuario (id)
);

CREATE TABLE tb_comentario (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    id_publicacao BIGINT       NOT NULL,
    id_usuario    BIGINT       NOT NULL,
    texto         VARCHAR(300) NOT NULL,
    momento       TIMESTAMP(6) NOT NULL,

    CONSTRAINT pk_comentario PRIMARY KEY (id),
    CONSTRAINT fk_comentario_publicacao FOREIGN KEY (id_publicacao) REFERENCES tb_publicacao (id),
    CONSTRAINT fk_comentario_usuario FOREIGN KEY (id_usuario) REFERENCES tb_usuario (id)
);

CREATE TABLE tb_denuncia (
    id_publicacao BIGINT       NOT NULL,
    id_usuario    BIGINT       NOT NULL,
    momento       TIMESTAMP(6) NOT NULL,

    CONSTRAINT pk_denuncia PRIMARY KEY (id_publicacao, id_usuario),
    CONSTRAINT fk_denuncia_publicacao FOREIGN KEY (id_publicacao) REFERENCES tb_publicacao (id),
    CONSTRAINT fk_denuncia_usuario FOREIGN KEY (id_usuario) REFERENCES tb_usuario (id)
);

CREATE TABLE tb_seguidor (
    id_seguidor BIGINT       NOT NULL,
    id_seguido  BIGINT       NOT NULL,
    momento     TIMESTAMP(6) NOT NULL,

    CONSTRAINT pk_seguidor PRIMARY KEY (id_seguidor, id_seguido),
    CONSTRAINT fk_seguidor_quem FOREIGN KEY (id_seguidor) REFERENCES tb_usuario (id),
    CONSTRAINT fk_seguidor_quem_e_seguido FOREIGN KEY (id_seguido) REFERENCES tb_usuario (id),
    CONSTRAINT ck_seguidor_nao_a_si CHECK (id_seguidor <> id_seguido)
);
