ALTER TABLE tb_usuario ADD COLUMN bloqueado BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE tb_usuario ADD COLUMN email_confirmado TIMESTAMP(6);
ALTER TABLE tb_usuario ADD COLUMN google_id VARCHAR(64);

CREATE UNIQUE INDEX uk_usuario_google ON tb_usuario (google_id) WHERE google_id IS NOT NULL;

CREATE TABLE tb_codigo_conta (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    id_usuario BIGINT       NOT NULL,
    tipo       VARCHAR(10)  NOT NULL,
    hash       CHAR(64)     NOT NULL,
    criado     TIMESTAMP(6) NOT NULL,
    expira     TIMESTAMP(6) NOT NULL,
    usado      TIMESTAMP(6),

    CONSTRAINT pk_codigo_conta PRIMARY KEY (id),
    CONSTRAINT uk_codigo_conta_hash UNIQUE (hash),
    CONSTRAINT fk_codigo_conta_usuario FOREIGN KEY (id_usuario) REFERENCES tb_usuario (id),
    CONSTRAINT ck_codigo_conta_tipo CHECK (tipo IN ('SENHA', 'EMAIL'))
);

CREATE INDEX ix_codigo_conta_usuario ON tb_codigo_conta (id_usuario, tipo, criado DESC);

CREATE TABLE tb_sugestao (
    id         BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    id_usuario BIGINT        NOT NULL,
    texto      VARCHAR(1000) NOT NULL,
    situacao   VARCHAR(20)   NOT NULL,
    momento    TIMESTAMP(6)  NOT NULL,

    CONSTRAINT pk_sugestao PRIMARY KEY (id),
    CONSTRAINT fk_sugestao_usuario FOREIGN KEY (id_usuario) REFERENCES tb_usuario (id),
    CONSTRAINT ck_sugestao_situacao CHECK (situacao IN ('ABERTO', 'RESOLVIDO', 'DESCARTADO'))
);

CREATE INDEX ix_sugestao_situacao ON tb_sugestao (situacao, momento DESC);

CREATE TABLE tb_foto_poi (
    id_poi       BIGINT       NOT NULL,
    tipo         VARCHAR(30)  NOT NULL,
    dados_base64 TEXT         NOT NULL,
    atualizado   TIMESTAMP(6) NOT NULL,

    CONSTRAINT pk_foto_poi PRIMARY KEY (id_poi),
    CONSTRAINT fk_foto_poi FOREIGN KEY (id_poi) REFERENCES tb_ponto_interesse (id),
    CONSTRAINT ck_foto_poi_tipo CHECK (tipo IN ('image/jpeg', 'image/png', 'image/webp'))
);
