-- =============================================================================
--  V6: missões com progresso verificado no servidor.
--
--  Na versão em Java, o próprio aplicativo informava quanto a pessoa tinha andado
--  (POST /progresso com qualquer número positivo), e um único pedido concluía
--  qualquer missão. Agora o progresso é calculado a partir de check-ins:
--
--    - um check-in só é aceito com a posição a até 30 m do ponto, uma vez por
--      ponto por dia;
--    - a distância entre dois check-ins seguidos do mesmo dia conta para as
--      missões de caminhada, limitada ao que dá para andar no tempo decorrido;
--    - o check-in no local de um evento, durante o evento, conta para as missões
--      de evento.
--
--  tb_progresso_missao (V1) fica sem uso: guardava o número autodeclarado. Não é
--  apagada para não perder o histórico de quem já usou o aplicativo.
-- =============================================================================

CREATE TABLE tb_checkin (
    id          BIGINT           GENERATED BY DEFAULT AS IDENTITY,
    id_usuario  BIGINT           NOT NULL,
    id_poi      BIGINT           NOT NULL,
    dia         DATE             NOT NULL,
    momento     TIMESTAMP(6)     NOT NULL,
    -- Metros creditados desde o check-in anterior do mesmo dia (0 no primeiro)
    metros      DOUBLE PRECISION NOT NULL,
    id_evento   BIGINT,

    CONSTRAINT pk_checkin PRIMARY KEY (id),
    CONSTRAINT uk_checkin_usuario_poi_dia UNIQUE (id_usuario, id_poi, dia),
    CONSTRAINT fk_checkin_usuario FOREIGN KEY (id_usuario) REFERENCES tb_usuario (id),
    CONSTRAINT fk_checkin_poi FOREIGN KEY (id_poi) REFERENCES tb_ponto_interesse (id),
    CONSTRAINT fk_checkin_evento FOREIGN KEY (id_evento) REFERENCES tb_evento (id),
    CONSTRAINT ck_checkin_metros CHECK (metros >= 0)
);

CREATE INDEX ix_checkin_usuario_momento ON tb_checkin (id_usuario, momento);

-- Missão concluída num período: '2026-11-11' (diária) ou '2026-W46' (semanal).
-- A pontuação do visitante é a soma das recompensas das conclusões.
CREATE TABLE tb_conclusao_missao (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    id_usuario  BIGINT       NOT NULL,
    id_missao   BIGINT       NOT NULL,
    periodo     VARCHAR(10)  NOT NULL,
    momento     TIMESTAMP(6) NOT NULL,

    CONSTRAINT pk_conclusao_missao PRIMARY KEY (id),
    CONSTRAINT uk_conclusao_usuario_missao_periodo UNIQUE (id_usuario, id_missao, periodo),
    CONSTRAINT fk_conclusao_usuario FOREIGN KEY (id_usuario) REFERENCES tb_usuario (id),
    CONSTRAINT fk_conclusao_missao FOREIGN KEY (id_missao) REFERENCES tb_missao (id)
);
